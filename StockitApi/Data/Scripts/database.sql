CREATE DATABASE StockitDB;
GO
USE StockitDB;
GO

CREATE TABLE [Role] (
    [Id] INT IDENTITY(1,1),
    [Name] NVARCHAR(50) NOT NULL,
    Description NVARCHAR(200) NULL,
    CONSTRAINT PK__ROLES__ID PRIMARY KEY (Id),
    CONSTRAINT UQ__ROLES__NAME UNIQUE ([Name])
);

CREATE TABLE [Permission] (
    [Id] INT IDENTITY(1,1),
    [Code] NVARCHAR(50) NOT NULL,
    Description NVARCHAR(200) NULL,
    CONSTRAINT PK__PERMISSIONS__ID PRIMARY KEY (Id),
    CONSTRAINT UQ__PERMISSIONS__CODE UNIQUE ([Code])
);

CREATE TABLE [RolePermission] (
    [RoleId] INT NOT NULL,
    [PermissionId] INT NOT NULL,
    CONSTRAINT PK__ROLEPERMISSIONS__ROLEID_PERMISSIONID PRIMARY KEY ([RoleId], [PermissionId]),
    CONSTRAINT FK__ROLEPERMISSIONS__ROLEID FOREIGN KEY ([RoleId]) REFERENCES [Role](Id),
    CONSTRAINT FK__ROLEPERMISSIONS__PERMISSIONID FOREIGN KEY ([PermissionId]) REFERENCES [Permission](Id)
);

CREATE TABLE [User] (
    [Id]            INT IDENTITY (1,1),
    [Username]      NVARCHAR(50) NOT NULL UNIQUE,
    [Email]         NVARCHAR(150) NOT NULL UNIQUE,
    [PasswordHash]  NVARCHAR(200) NOT NULL,
    [FullName]      NVARCHAR(150) NOT NULL,
    [RoleId]        INT NOT NULL,
    [IsActive]      BIT NOT NULL DEFAULT 1,
    [CreatedAt]     DATETIME NOT NULL DEFAULT GETUTCDATE(),
    [CreatedBy]     INT NULL,
    [LastLoginAt]   DATETIME NULL,
    CONSTRAINT PK__USERS__ID PRIMARY KEY (Id),
    CONSTRAINT FK__USERS__ROLEID FOREIGN KEY (RoleId) REFERENCES [Role](Id)
);

CREATE TABLE [RefreshToken] (
    [Id] INT IDENTITY(1,1),
    [UserId] INT NOT NULL,
    [TokenHash] NVARCHAR(200) NOT NULL,
    [ExpiresAt] DATETIME NOT NULL,
    [RevokedAt] DATETIME NULL,
    [CreatedAt] DATETIME NOT NULL DEFAULT GETUTCDATE(),
    [CreatedByIp] NVARCHAR(45) NOT NULL,
    [UserAgent] NVARCHAR(200) NULL,
    [DeviceName] NVARCHAR(100) NULL,
    CONSTRAINT PK__REFRESHTOKENS__ID PRIMARY KEY (Id),
    CONSTRAINT FK__REFRESHTOKENS__USERID FOREIGN KEY (UserId) REFERENCES [User](Id)
);
